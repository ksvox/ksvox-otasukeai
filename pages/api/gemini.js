// 歌詞に日本語（ひらがな・カタカナ・漢字）が含まれるかチェック
function containsJapanese(text) {
  return /[\u3040-\u30ff\u3400-\u4dbf\u4e00-\u9fff]/.test(text || '');
}

// GeminiのレスポンステキストからJSON部分だけを取り出す
function extractJson(text) {
  const cleaned = (text || '').replace(/```json/gi, '').replace(/```/g, '').trim();
  const start = cleaned.indexOf('{');
  const end = cleaned.lastIndexOf('}');
  if (start === -1 || end === -1) {
    throw new Error('AIの応答からJSONを取り出せませんでした');
  }
  return JSON.parse(cleaned.slice(start, end + 1));
}

export default async function handler(req, res) {
  if (req.method !== 'POST') {
    res.status(405).json({ error: 'Method Not Allowed' });
    return;
  }

  const { artist, song, tempo, lyrics } = req.body || {};

  if (!lyrics || !lyrics.trim()) {
    res.status(400).json({ error: '歌詞が入力されていません。' });
    return;
  }

  if (containsJapanese(lyrics)) {
    res.status(400).json({ error: '英語曲の歌詞を入力してください。' });
    return;
  }

  const apiKey = process.env.GEMINI_API_KEY;
  if (!apiKey) {
    res.status(500).json({ error: 'サーバー側にGEMINI_API_KEYが設定されていません。' });
    return;
  }

  const systemPrompt = buildSystemPrompt({ artist, song, tempo });

  try {
    const response = await fetch(
      `https://generativelanguage.googleapis.com/v1beta/models/gemini-3.5-flash:generateContent?key=${apiKey}`,
      {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          system_instruction: {
            parts: [{ text: systemPrompt }],
          },
          contents: [
            {
              role: 'user',
              parts: [{ text: `以下の英語歌詞を解析してください。\n\n${lyrics}` }],
            },
          ],
          generationConfig: {
            temperature: 0.4,
            responseMimeType: 'application/json',
          },
        }),
      }
    );

    if (!response.ok) {
      const errText = await response.text();
      console.error('Gemini API error:', errText);
      res.status(502).json({ error: 'Gemini APIとの通信でエラーが発生しました。' });
      return;
    }

    const data = await response.json();
    const text = data?.candidates?.[0]?.content?.parts?.[0]?.text || '';
    const parsed = extractJson(text);

    res.status(200).json(parsed);
  } catch (err) {
    console.error('otasuke-ai gemini handler error:', err);
    res.status(500).json({ error: '解析中にエラーが発生しました。もう一度お試しください。' });
  }
}
